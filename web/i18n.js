export const strings = { en, zh };

const preferred = globalThis.navigator?.languages?.[0] || globalThis.navigator?.language || "";
/** BCP 47 tag of the UI language, for <html lang> and date formatting. */
export const lang = /^zh(-|$)/i.test(preferred) ? "zh-CN" : "en";
const table = lang === "zh-CN" ? zh : en;

/** Look up a UI string and fill its {placeholders} from params. */
export function t(key, params = {}) {
  const value = table[key] ?? en[key] ?? key;
  if (typeof value === "function") return value(params);
  return value.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

/** Fill the static text marked with data-i18n / data-i18n-placeholder in index.html. */
export function translatePage(root = document) {
  document.documentElement.lang = lang;
  for (const element of root.querySelectorAll("[data-i18n]")) element.textContent = t(element.dataset.i18n);
  for (const element of root.querySelectorAll("[data-i18n-placeholder]")) {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  }
}
